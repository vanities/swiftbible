def localize_strings(config_dict, locale, text_keys):
    """Return a copy of config_dict with text_keys translated to locale.

    Falls back to English if locale or string is missing.
    """
    if locale == "en-US":
        return config_dict
    locale_map = TRANSLATIONS.get(locale, {})
    new = dict(config_dict)
    for key in text_keys:
        if key in new and isinstance(new[key], str):
            new[key] = locale_map.get(new[key], new[key])
    return new


def localize_config_list(config_list, locale, text_keys=None):
    """Return a copy of config_list (list of dicts) with text_keys translated."""
    if locale == "en-US":
        return config_list
    if text_keys is None:
        text_keys = ["headline", "subtitle", "left_headline", "left_subtitle",
                     "right_headline", "right_subtitle"]
    return [localize_strings(item, locale, text_keys) for item in config_list]

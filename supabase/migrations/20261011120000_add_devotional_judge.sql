-- Quality gate for AI-generated daily devotionals.
--
-- daily-devotional now grades every draft with a judge model before saving
-- (supabase/functions/_shared/devotional-judge.ts). A draft below the
-- threshold is never published: it is recorded here and the function
-- regenerates on the same track/type/testament from a different verse.
--
-- Two changes:
--
--   "Daily Devotional".judge  — the judge result for the published row:
--                               { model, attempt, attempts, exhausted,
--                                 result: { version, scores, overall,
--                                 threshold, hard_fails, passed, reasons },
--                                 error? }.
--                               result.passed = false only when every attempt
--                               failed and the best draft was published anyway
--                               (exhausted = true). result = null means the
--                               judge call itself failed and the draft was
--                               published unjudged. NULL column = custom or
--                               pre-judge row.
--
--   daily_devotional_rejections — every draft the judge failed. A separate
--                               table, not a status column, so nothing that
--                               reads "Daily Devotional" (the apps via
--                               get-daily-devotional, the track rotation, the
--                               existing-row cache check) can pick one up.
--                               Several rows per for_date are expected.

ALTER TABLE public."Daily Devotional"
  ADD COLUMN IF NOT EXISTS judge JSONB;

COMMENT ON COLUMN public."Daily Devotional".judge IS
  'Judge result for the published draft: {model, attempt, attempts, exhausted, result, error?}. NULL for custom devotionals or rows predating the judge.';

CREATE TABLE IF NOT EXISTS public.daily_devotional_rejections (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  for_date               DATE        NOT NULL,
  attempt                INT         NOT NULL,
  track                  TEXT,
  prompt_version         TEXT,
  devotional_type        TEXT,
  testament              TEXT,
  verses                 JSONB,
  holiday_name           TEXT,
  message                TEXT        NOT NULL,
  prompt                 TEXT,
  verse_selection_prompt TEXT,
  model                  TEXT,
  usage                  JSONB,
  judge_model            TEXT,
  judge_version          TEXT,
  judge_score            NUMERIC(4, 1),
  judge_threshold        NUMERIC(4, 1),
  judge                  JSONB
);

COMMENT ON TABLE public.daily_devotional_rejections IS
  'AI devotional drafts that failed the judge and were not published. Written by the daily-devotional Edge Function; never read by the apps.';

CREATE INDEX IF NOT EXISTS daily_devotional_rejections_for_date_idx
  ON public.daily_devotional_rejections (for_date);
CREATE INDEX IF NOT EXISTS daily_devotional_rejections_track_idx
  ON public.daily_devotional_rejections (track);

-- Server-side only, same posture as "Daily Devotional" after
-- 20260529162804_lock_daily_devotional_direct_reads.sql: RLS on with no
-- policies, no anon/authenticated grants.
ALTER TABLE public.daily_devotional_rejections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.daily_devotional_rejections FROM anon;
REVOKE ALL ON TABLE public.daily_devotional_rejections FROM authenticated;
GRANT ALL ON TABLE public.daily_devotional_rejections TO service_role;

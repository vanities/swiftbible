-- Quality judgments for generated daily devotionals.
-- Every failed judgment is audited before retrying. A soft-score fallback
-- may subsequently be published; hard failures and floor-level criteria may
-- not. run_id + attempt link an audit to Daily Devotional.judge metadata.
-- Published metadata contains model, run_id, attempt, attempts, exhausted,
-- result, and optional error (judge unavailable) or retry_error.
-- NULL judge means a custom row or content predating the quality gate.

ALTER TABLE public."Daily Devotional"
  ADD COLUMN IF NOT EXISTS judge JSONB;

COMMENT ON COLUMN public."Daily Devotional".judge IS
  'Judge result for the published draft: {model, run_id, attempt, attempts, exhausted, result, error?, retry_error?}. NULL for custom devotionals or rows predating the judge.';

CREATE TABLE IF NOT EXISTS public.daily_devotional_rejections (
  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  run_id                 UUID        NOT NULL,
  for_date               DATE        NOT NULL,
  attempt                INT         NOT NULL,
  track                  TEXT,
  prompt_version         TEXT,
  devotional_type        TEXT,
  testament              TEXT,
  verses                 JSONB,
  holiday_name           TEXT,
  message                TEXT        NOT NULL,
  prompt                 TEXT,
  verse_selection_prompt TEXT,
  model                  TEXT,
  usage                  JSONB,
  judge_model            TEXT,
  judge_version          TEXT,
  judge_score            NUMERIC(4, 1),
  judge_threshold        NUMERIC(4, 1),
  judge                  JSONB,
  UNIQUE (run_id, attempt)
);

COMMENT ON TABLE public.daily_devotional_rejections IS
  'Every failed AI judgment, persisted before retrying. A soft-score fallback may also be published; match run_id and attempt to the published judge metadata. Never read by the apps.';

CREATE INDEX IF NOT EXISTS daily_devotional_rejections_for_date_idx
  ON public.daily_devotional_rejections (for_date);
CREATE INDEX IF NOT EXISTS daily_devotional_rejections_track_idx
  ON public.daily_devotional_rejections (track);

-- Server-side only, same posture as "Daily Devotional" after
-- 20260529162804_lock_daily_devotional_direct_reads.sql: RLS on with no
-- policies, no anon/authenticated grants.
ALTER TABLE public.daily_devotional_rejections ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.daily_devotional_rejections FROM anon;
REVOKE ALL ON TABLE public.daily_devotional_rejections FROM authenticated;
GRANT ALL ON TABLE public.daily_devotional_rejections TO service_role;

/// Small tinted pill indicating the prompting style ("track") that produced
/// an AI-generated devotional. Driven by the `track` column on the Daily
/// Devotional row (set by the Edge Function's TRACK_CYCLE).
struct DevotionalStyleChip: View {
    let track: String

    @State private var showInfo = false

    private var emoji: String? {
        switch track {
        case "empathy": return "💗"
        case "technical": return "🧠"
        case "narrative": return "🌅"
        case "practical": return "🛠️"
        default: return nil
        }
    }

    private var label: String? {
        switch track {
        case "empathy": return "Empathy"
        case "technical": return "Technical"
        case "narrative": return "Narrative"
        case "practical": return "Practical"
        default: return nil
        }
    }

    private var tint: Color {
        switch track {
        case "empathy": return .pink
        case "technical": return .indigo
        case "narrative": return .orange
        case "practical": return .green
        default: return .secondary
        }
    }

    private var infoText: String {
        switch track {
        case "empathy": return AIAttribution.styleEmpathy
        case "technical": return AIAttribution.styleTechnical
        case "narrative": return AIAttribution.styleNarrative
        case "practical": return AIAttribution.stylePractical
        default: return ""
        }
    }

    var body: some View {
        if let emoji, let label {
            Button { showInfo = true } label: {
                HStack(spacing: 4) {
                    Text(emoji)
                    Text(label)
                        .fontWeight(.medium)
                }
                .font(.caption)
                .padding(.horizontal, 8)
                .padding(.vertical, 3)
                .background(tint.opacity(0.15), in: Capsule())
                .overlay(Capsule().stroke(tint.opacity(0.35), lineWidth: 0.5))
                .foregroundStyle(tint)
            }
            .buttonStyle(.plain)
            .accessibilityLabel("\(label) style. Tap to learn more.")
            .alert("\(label) style", isPresented: $showInfo) {
                Button("OK", role: .cancel) {}
            } message: {
                Text(infoText)
            }
        }
    }
}


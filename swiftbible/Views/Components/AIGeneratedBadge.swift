    // swiftlint:disable:next cyclomatic_complexity function_body_length
    static func palette(for name: String) -> HolidayBadgePalette {
        switch name {
        // ── Christmas cycle: red + green + gold ──
        case "Christmas Day":
            return .init(primary: .brandRed, secondary: .brandGreen, tertiary: .brandGold, symbol: "gift.fill")
        case "Christmas Eve":
            return .init(primary: .brandRed, secondary: .brandGreen, tertiary: .brandGoldLight, symbol: "moon.stars.fill")

        // ── Advent: violet + rose for Gaudete (3rd Sunday) ──
        case "First Sunday of Advent":
            return .init(primary: .purple, secondary: .brandDeepNavy, tertiary: .brandGold, symbol: "1.circle.fill")
        case "Second Sunday of Advent":
            return .init(primary: .purple, secondary: .brandDeepNavy, tertiary: .brandGold, symbol: "2.circle.fill")
        case "Third Sunday of Advent":
            return .init(primary: .pink, secondary: .purple, tertiary: .brandGold, symbol: "3.circle.fill")
